import type { ColumnSpec, DatabaseEngine } from "@ucch/protocol";
import { DbQueryError } from "./adapter.js";
import { quoteIdent, quoteLiteral } from "./sql-ident.js";

/**
 * A column definition as each engine spells it.
 *
 * The type text is the user's own, validated to characters a type can
 * contain; the engine is the one that knows whether `varchar(3, 4)` means
 * anything, and its error is the one shown.
 */
export function columnDdl(engine: DatabaseEngine, spec: ColumnSpec): string {
  const parts = [quoteIdent(engine, spec.name), spec.type];
  if (spec.autoincrement) {
    if (engine === "mysql") parts.push("NOT NULL AUTO_INCREMENT");
    else {
      if (!/^(small|big)?int/i.test(spec.type.trim()) && !/serial/i.test(spec.type)) {
        throw new DbQueryError("only an integer column can auto-increment");
      }
      parts.push("NOT NULL GENERATED BY DEFAULT AS IDENTITY");
    }
  } else {
    parts.push(spec.nullable && !spec.primaryKey ? "NULL" : "NOT NULL");
  }
  if (spec.default && !spec.autoincrement) parts.push(`DEFAULT ${defaultSql(engine, spec.default)}`);
  if (engine === "mysql" && spec.comment) parts.push(`COMMENT ${quoteLiteral(engine, spec.comment)}`);
  return parts.join(" ");
}

export function defaultSql(engine: DatabaseEngine, value: NonNullable<ColumnSpec["default"]>): string {
  if (value.kind === "literal") return quoteLiteral(engine, value.value);
  // MySQL wants expression defaults parenthesised, except the timestamp ones.
  if (engine === "mysql" && !/^(CURRENT_TIMESTAMP|NOW\(\)|NULL)$/i.test(value.value.trim())) return `(${value.value})`;
  return value.value;
}
