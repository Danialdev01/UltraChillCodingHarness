/**
 * The entries matching a query, the closer the earlier: a name that starts
 * with it, then a name that contains it, then a keyword either way. Nothing
 * typed lists everything in order.
 */
export function searchEmoji(query: string, list: readonly EmojiEntry[] = EMOJI): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...list];
  const rank = (entry: EmojiEntry): number => {
    if (entry.name.startsWith(q)) return 0;
    if (entry.name.includes(q)) return 1;
    if (entry.keywords.some((k) => k.startsWith(q))) return 2;
    if (entry.keywords.some((k) => k.includes(q))) return 3;
    return -1;
  };
  return list
    .map((entry, order) => ({ entry, order, rank: rank(entry) }))
    .filter((r) => r.rank !== -1)
    .sort((a, b) => a.rank - b.rank || a.order - b.order)
    .map((r) => r.entry);
}

/** Any one of them, for a page that just wants an icon. */
export function randomEmoji(random: () => number = Math.random): string {
  return EMOJI[Math.floor(random() * EMOJI.length)]!.char;
}
