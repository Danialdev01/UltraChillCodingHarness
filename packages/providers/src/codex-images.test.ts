import { mkdtemp, mkdir, readFile, rm, symlink, writeFile, appendFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { afterEach, describe, expect, it } from "vitest";
import type { DomainEvent } from "@ucch/protocol";
import { codexRollout, importCodexImage, rolloutImagePaths, withCodexImages } from "./codex-images.js";
import { CodexProvider } from "./codex.js";
import { FakeProcessHost, stdout } from "./testing.js";
import type { ProviderRunInput } from "./types.js";

const cleanups: string[] = [];
afterEach(async () => { for (const path of cleanups.splice(0)) await rm(path, { recursive: true, force: true }); });
async function setup() {
  const base = await mkdtemp(join(tmpdir(), "ucch-images-"));
  cleanups.push(base);
  const cwd = join(base, "workspace");
  const home = join(base, "codex");
  await mkdir(cwd);
  await mkdir(join(home, "generated_images"), { recursive: true });
  const source = join(home, "generated_images", "dog.png");
  await writeFile(source, Buffer.from("image bytes"));
  const input: ProviderRunInput = { ctx: { cwd, env: { CODEX_HOME: home }, host: new FakeProcessHost([]) }, prompt: "Generate a dog image", projectId: "11111111-1111-4111-8111-111111111111", threadId: "22222222-2222-4222-8222-222222222222", turnId: "33333333-3333-4333-8333-333333333333" };
  return { base, cwd, home, source, input };
}

describe("Codex image artifacts", () => {
  it("copies generated bytes into a durable workspace image without overwriting earlier images", async () => {
    const { input, source, cwd } = await setup();
    const first = await importCodexImage(input, source);
    expect(first).toMatch(/^\.ucch\/generated-images\//);
    expect(await readFile(join(cwd, first), "utf8")).toBe("image bytes");
    await writeFile(source, "new image");
    const next = await importCodexImage(input, source);
    expect(next).not.toBe(first);
    expect(await readFile(join(cwd, first), "utf8")).toBe("image bytes");
    expect(await importCodexImage(input, join(cwd, next))).toBe(next);
  });

  it("refuses unrelated files and symlinks that escape the source or destination", async () => {
    const { input, base, home, cwd } = await setup();
    const secret = join(base, "secret.png");
    await writeFile(secret, "private");
    await expect(importCodexImage(input, secret)).rejects.toThrow(/outside/);
    const link = join(home, "generated_images", "link.png");
    await symlink(secret, link);
    await expect(importCodexImage(input, link)).rejects.toThrow(/outside/);
    await symlink(base, join(cwd, ".ucch"));
    await expect(importCodexImage(input, join(home, "generated_images", "dog.png"))).rejects.toThrow(/escapes/);
  });

  it("recovers only this turn's images from the exact resumed thread, before turn completion", async () => {
    const { input, home, source } = await setup();
    const session = "abc-123";
    const dir = join(home, "sessions", "2026", "11", "10");
    await mkdir(dir, { recursive: true });
    const path = join(dir, `rollout-2026-11-10-${session}.jsonl`);
    await writeFile(path, JSON.stringify({ type: "event_msg", payload: { type: "image_generation_end", saved_path: "/old/not-available.png" } }) + "\n");
    await writeFile(join(dir, "rollout-other-session.jsonl"), JSON.stringify({ type: "event_msg", payload: { type: "image_generation_end", saved_path: "/other/private.png" } }) + "\n");
    expect(codexRollout(home, session)).toBe(path);
    const completed: DomainEvent = { type: "agent.turn_completed", threadId: input.threadId, turnId: input.turnId, stopReason: "end_turn", usage: { inputTokens: 1, outputTokens: 1, cacheReadInputTokens: 0, cacheCreationInputTokens: 0 }, costUsd: 0 };
    const run = withCodexImages({ ...input, resumeToken: session }, () => ({
      interrupt: async () => {}, kill: async () => {},
      events: { async *[Symbol.asyncIterator]() {
        await appendFile(path, JSON.stringify({ type: "event_msg", payload: { type: "image_generation_end", saved_path: source } }) + "\n");
        yield completed;
      } },
    }), () => session, () => []);
    const events: DomainEvent[] = [];
    for await (const event of run.events) events.push(event);
    expect(events.map((e) => e.type)).toEqual(["agent.text_delta", "agent.message", "agent.turn_completed"]);
    expect(JSON.stringify(events)).toContain("![Generated image]");
    expect(JSON.stringify(events)).not.toContain("not-available");
    expect(JSON.stringify(events)).not.toContain("private");
  });

  it("publishes image items even without a rollout file", async () => {
    const { input, source } = await setup();
    input.ctx.host = new FakeProcessHost([{ match: () => true, lines: [
      stdout(JSON.stringify({ type: "item.completed", item: { type: "image_generation", id: "image1", saved_path: source, status: "completed" } })),
      stdout(JSON.stringify({ type: "turn.completed", usage: {} })),
    ] }]);
    const events: DomainEvent[] = [];
    for await (const event of new CodexProvider("codex").run(input).events) events.push(event);
    expect(events.map((e) => e.type)).toEqual(["agent.text_delta", "agent.message", "agent.turn_completed"]);
  });

  it("does not display an image twice when Codex already included it in Markdown", async () => {
    const { input, source } = await setup();
    const path = await importCodexImage(input, source);
    const text = `![Dog](<${path}>)`;
    input.ctx.host = new FakeProcessHost([{ match: () => true, lines: [
      stdout(JSON.stringify({ type: "item.completed", item: { type: "agent_message", text } })),
      stdout(JSON.stringify({ type: "item.completed", item: { type: "image_generation", saved_path: source, status: "completed" } })),
      stdout(JSON.stringify({ type: "turn.completed", usage: {} })),
    ] }]);
    const events: DomainEvent[] = [];
    for await (const event of new CodexProvider("codex").run(input).events) events.push(event);
    expect(events.filter((event) => event.type === "agent.message")).toHaveLength(1);
    expect(events.at(-1)?.type).toBe("agent.turn_completed");
  });

  it("ignores failed generations and arbitrary path-bearing tool output", () => {
    expect(rolloutImagePaths({ type: "command_execution", saved_path: "/private.png" })).toEqual([]);
    expect(rolloutImagePaths({ type: "image_generation", status: "failed", saved_path: "/private.png" })).toEqual([]);
  });
});
